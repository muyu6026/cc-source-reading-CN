export type ModelKey = keyof typeof ALL_MODEL_CONFIGS
// ModelKey 类型：配置对象的键联合类型。

/** Union of all canonical first-party model IDs, e.g. 'claude-opus-4-6' | 'claude-sonnet-4-5-20250929' | … */
export type CanonicalModelId =
  (typeof ALL_MODEL_CONFIGS)[ModelKey]['firstParty']
// CanonicalModelId 类型：所有 firstParty 模型标识的联合类型。

/** Runtime list of canonical model IDs — used by comprehensiveness tests. */
export const CANONICAL_MODEL_IDS = Object.values(ALL_MODEL_CONFIGS).map(
  c => c.firstParty,
) as [CanonicalModelId, ...CanonicalModelId[]]
// CANONICAL_MODEL_IDS：运行期模型标识列表，供完整性测试使用。

/** Map canonical ID → internal short key. Used to apply settings-based modelOverrides. */
export const CANONICAL_ID_TO_KEY: Record<CanonicalModelId, ModelKey> =
  Object.fromEntries(
    (Object.entries(ALL_MODEL_CONFIGS) as [ModelKey, ModelConfig][]).map(
      ([key, cfg]) => [cfg.firstParty, key],
    ),
  ) as Record<CanonicalModelId, ModelKey>
// CANONICAL_ID_TO_KEY：规范标识到内部短名的映射，用于套用设置里的模型覆盖。
