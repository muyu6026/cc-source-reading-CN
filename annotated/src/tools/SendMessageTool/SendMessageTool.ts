// StructuredMessage 判别联合：三种跨代理协议消息——shutdown_request（请求对方关机）、shutdown_response（批准/拒绝关机）、plan_approval_response（计划审批回执）。普通文本走 z.string 分支，结构化消息走这里，inputSchema 用 union 合并两条路。
const StructuredMessage = lazySchema(() =>
  z.discriminatedUnion('type', [
    z.object({
      type: z.literal('shutdown_request'),
      reason: z.string().optional(),
    }),
    z.object({
      type: z.literal('shutdown_response'),
      request_id: z.string(),
      approve: semanticBoolean(),
      reason: z.string().optional(),
    }),
    z.object({
      type: z.literal('plan_approval_response'),
      request_id: z.string(),
      approve: semanticBoolean(),
      feedback: z.string().optional(),
    }),
  ]),
)

// inputSchema 三字段：to（收件人——队友名/「*」广播/uds: 本地 socket/bridge: 跨机会话）、summary（5-10 词摘要，字符串消息必填）、message（字符串或结构化消息）。to 的 describe 按 UDS_INBOX 特性分档——功能没开时模型根本看不到 bridge 语法。
const inputSchema = lazySchema(() =>
  z.object({
    to: z
      .string()
      .describe(
        feature('UDS_INBOX')
          ? 'Recipient: teammate name, "*" for broadcast, "uds:<socket-path>" for a local peer, or "bridge:<session-id>" for a Remote Control peer (use ListPeers to discover)'
          : 'Recipient: teammate name, or "*" for broadcast to all teammates',
      ),
    summary: z
      .string()
      .optional()
      .describe(
        'A 5-10 word summary shown as a preview in the UI (required when message is a string)',
      ),
    message: z.union([
      z.string().describe('Plain text message content'),
      StructuredMessage(),
    ]),
  }),
)
type InputSchema = ReturnType<typeof inputSchema>

export type Input = z.infer<InputSchema>

